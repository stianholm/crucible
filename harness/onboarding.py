MEASUREMENT_CHOICES = ("automated_checks", "labelled_examples", "judge", "none_yet")


@dataclass
class OnboardingAnswers:
    q1_what: str  # what should get better, one sentence
    q2_form: str  # what form the artifact takes
    q3_invocation: str  # how it's invoked — FROZEN forever once answered
    q4_mutation_surface: str  # what the proposer may change vs frozen scaffolding
    q5_good_vs_bad: str  # how to tell good from bad, even informally
    q6_measurement: str  # one of MEASUREMENT_CHOICES
    q7_executes_code: bool  # whether evaluating a candidate runs code
    # Optional eighth question, added 2026-10-18 (TODO.md decision 80): the
    # written standard the solution must meet, if one exists. It is given to the
    # proposer from the first generation. capability_case spent weeks of search
    # rediscovering a rule the proposer was never told; stated in the task
    # description, its first generation reached held-out 0.972 (decision 79).
    q8_standard: str = ""

    def __post_init__(self) -> None:
        if self.q6_measurement not in MEASUREMENT_CHOICES:
            raise ValueError(
                f"q6_measurement must be one of {MEASUREMENT_CHOICES}, got {self.q6_measurement!r}"
            )


def slugify(text: str) -> str:
    # underscore, not kebab-case: solution_id doubles as a Python package
    # name throughout harness/*.py (import_module(f"solutions.{solution_id}...")),
    # and hyphens aren't legal in a Python identifier. Found the hard way
    # onboarding the second real solution — the fixture's single-word id
    # never exercised this path.
    s = re.sub(r"[^a-z0-9]+", "_", text.lower()).strip("_")
    return s or "solution"


def measurement_recommendation(answer: str) -> str | None:
    """Question six's recommendation. See PHASE-1.md task 1.1."""
    if answer in ("labelled_examples", "judge"):
        return (
            "Automated checks are preferred over labels or judged scoring where "
            "possible: they give partial credit for free, keep the noise floor "
            "small, can't be argued into a good score, and don't compete with "
            "the proposer for GPU memory bandwidth the way judge calls do. "
            "Reconsider whether some of this can be checked programmatically "
            "before committing to this answer."
        )
    return None


def render_solution_md(solution_id: str, a: OnboardingAnswers) -> str:
    rec = measurement_recommendation(a.q6_measurement)
    rec_block = f"\n**Recommendation given at onboarding time:** {rec}\n" if rec else ""
    return f"""# {solution_id}

Generated by the onboarding wizard from the seven questions. Do not hand-edit
this file — re-run onboarding if an answer changes, except question three
(invocation), which is frozen forever once set.

## What should get better

{a.q1_what}

## Artifact

{a.q2_form}

## Invocation — FROZEN

{a.q3_invocation}

If this ever changes, every score in this solution's archive becomes
incomparable and the solution starts over. Onboard a new solution instead
of editing this.

## Mutation surface

{a.q4_mutation_surface}

The proposer may only rewrite what's between `EVOLVE-BLOCK-START` and
`EVOLVE-BLOCK-END` in `candidate/`. Everything else is frozen scaffolding.

## How good is told from bad

{a.q5_good_vs_bad}

## Measurement

Answer: `{a.q6_measurement}`
{rec_block}
## Evaluator

`executes_code: {str(a.q7_executes_code).lower()}` — {"the sandboxed evaluator is used." if a.q7_executes_code else "the in-process evaluator is used."}

## Standard given to the proposer

{a.q8_standard or "None stated. Search has to discover what good looks like from the fitness alone."}
"""


def render_solution_yaml(solution_id: str, a: OnboardingAnswers) -> str:
    return yaml.safe_dump(
        {
            "solution_id": solution_id,
            "what": a.q1_what,
            "form": a.q2_form,
            "invocation": a.q3_invocation,
            "mutation_surface": a.q4_mutation_surface,
            "good_vs_bad": a.q5_good_vs_bad,
            "measurement": a.q6_measurement,
            "executes_code": a.q7_executes_code,
            "standard": a.q8_standard,
        },
        sort_keys=False,
    )


def task_description(sol_dir: Path) -> str:
    """What the proposer is told the component must do: question one's answer,
    plus the standard from question eight when there is one."""
    meta = yaml.safe_load((sol_dir / "solution.yaml").read_text())
    standard = (meta.get("standard") or "").strip()
    return meta["what"] + (f"\n\nThe standard it must meet: {standard}" if standard else "")


def onboard(solution_id: str, answers: OnboardingAnswers, root: Path) -> Path:
    """Create solutions/<solution_id>/ from the seven answers. Idempotent on
    the metadata files; does not touch candidate/, checks/, or data/ if they
    already exist (those are built by later onboarding steps or by hand for
    a real solution, not regenerated on every wizard re-run)."""
    sol_dir = root / "solutions" / solution_id
    sol_dir.mkdir(parents=True, exist_ok=True)
    (sol_dir / "SOLUTION.md").write_text(render_solution_md(solution_id, answers))
    (sol_dir / "solution.yaml").write_text(render_solution_yaml(solution_id, answers))
    for sub in ("candidate", "checks", "data"):
        (sol_dir / sub).mkdir(exist_ok=True)
    for sub in ("dev", "rotation", "held_out"):
        (sol_dir / "data" / sub).mkdir(exist_ok=True)
    return sol_dir
