"""The onboarding wizard. See PHASE-1.md task 1.1.

Asks the seven questions and produces a complete solution directory —
nothing in solutions/<id>/ is hand-edited on first creation. Run via
`python -m harness.cli onboard`.
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from pathlib import Path

import yaml

